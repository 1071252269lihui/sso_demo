package com.example.sso_server.entity;

import lombok.NoArgsConstructor;
import lombok.ToString;
import org.springframework.security.core.GrantedAuthority;
import org.springframework.security.core.userdetails.UserDetails;
import org.springframework.util.CollectionUtils;

import java.util.ArrayList;
import java.util.Collection;
import java.util.List;

@ToString(callSuper = true)
@NoArgsConstructor
public class CustomUserDetailsEntity extends SsUserEntity implements UserDetails  {

    public CustomUserDetailsEntity(List<SsAuthorityEntity> authorities){
        if (!CollectionUtils.isEmpty(authorities)) {
            this.authorities = authorities;
        }
    }

    private List<SsAuthorityEntity> authorities = new ArrayList<>();

    @Override
    public Collection<? extends GrantedAuthority> getAuthorities() {
        return authorities;
    }

    @Override
    public String getPassword() {
        return super.getPassword();
    }

    @Override
    public String getUsername() {
        return super.getUsername();
    }

    @Override
    public boolean isAccountNonExpired() {
        return true;
    }

    @Override
    public boolean isAccountNonLocked() {
        return true;
    }

    @Override
    public boolean isCredentialsNonExpired() {
        return true;
    }

    @Override
    public boolean isEnabled() {
        return true;
    }
}
